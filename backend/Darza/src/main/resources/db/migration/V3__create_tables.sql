CREATE TABLE towns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    city_id BIGINT NOT NULL REFERENCES cities(id),
    name VARCHAR(100) NOT NULL,
    CONSTRAINT unique_town_to_city UNIQUE (city_id,name)
);
CREATE TABLE users(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    display_name VARCHAR(100) NOT NULL ,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL ,
    phone_number VARCHAR(20) NOT NULL ,
    role VARCHAR(20) NOT NULL DEFAULT 'PUBLISHER' CHECK ( role in ('ADMIN','PUBLISHER')),
    town_id BIGINT REFERENCES towns(id),
    address VARCHAR(255),
    profile_image_path VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE properties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    title VARCHAR(150) NOT NULL ,
    description TEXT,
    property_type VARCHAR(20) NOT NULL CHECK ( property_type in('APARTMENT','HOUSE','VILLA','LAND','COMMERCIAL','OTHER') ),
    listing_type VARCHAR(10) NOT NULL CHECK ( listing_type in ('SELL','RENT')),
    price NUMERIC(12,2) NOT NULL CHECK ( price >=0 ),
    currency VARCHAR(3) NOT NULL CHECK ( currency in ('ILS','JOD','USD')),
    rent_period VARCHAR(20) CHECK ( rent_period in ('MONTHLY','YEARLY')),
    area_size NUMERIC(10,2),
    rooms smallint CHECK ( rooms>=0 ),
    bathrooms smallint CHECK ( bathrooms>=0),
    furnished BOOLEAN,
    has_balcony BOOLEAN,
    town_id BIGINT NOT NULL REFERENCES towns(id),
    address VARCHAR(150),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    posting_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK ( posting_status in ('PENDING','APPROVED','REJECTED') ),
    rejection_reason TEXT,
    approved_at TIMESTAMPTZ,
    approved_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT NOT NULL REFERENCES users(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_listing_rent_period CHECK (
        (listing_type='RENT') = (rent_period IS NOT NULL )
        ),
    CONSTRAINT chk_posting_status_approved CHECK (
        (posting_status='APPROVED')=(approved_at IS NOT NULL AND approved_by IS NOT NULL )
        )
);

CREATE INDEX idx_feed_posts ON properties (approved_at desc ) WHERE posting_status='APPROVED' AND is_available;

CREATE TABLE property_images(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id BIGINT NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
    image_path VARCHAR(500) NOT NULL ,
);